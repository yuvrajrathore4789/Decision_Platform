'use strict';
/**
 * Runs the real workflow engine (no DB needed) against sample inputs and writes docs/decision_examples.md.
 *   npm run examples
 */
process.env.NODE_ENV = 'test';
process.env.RETRY_BASE_MS = '0';
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const engine = require('../src/engine/workflowEngine');
const audit = require('../src/services/audit.service');
const { sha256 } = require('../src/utils/hash');

const load = (f) => yaml.load(fs.readFileSync(path.join(__dirname, '..', 'config', 'workflows', f), 'utf8'));
const DEFS = { loan_approval: load('loan_approval.yaml'), vendor_approval: load('vendor_approval.yaml') };

function makeRequest(workflow, payload) {
  const def = DEFS[workflow];
  return {
    _id: 'example', workflow, workflowVersion: def.version, payload, payloadHash: sha256(payload),
    status: 'RECEIVED', currentStage: def.start, context: {}, attempts: {}, decision: null,
    stateHistory: [], auditLog: [], save: async () => {},
  };
}

const scenarios = [
  { title: '1. Happy path: loan APPROVED', workflow: 'loan_approval',
    payload: { applicant_id: 'A-1001', income: 60000, loan_amount: 150000, age: 30, mock_credit_score: 720 } },
  { title: '2. Mandatory check fails: loan REJECTED (underage)', workflow: 'loan_approval',
    payload: { applicant_id: 'A-1002', income: 60000, loan_amount: 10000, age: 16 } },
  { title: '3. Threshold check fails: loan sent to MANUAL_REVIEW', workflow: 'loan_approval',
    payload: { applicant_id: 'A-1003', income: 40000, loan_amount: 400000, age: 35, mock_credit_score: 700 } },
  { title: '4. Credit score too low: loan REJECTED', workflow: 'loan_approval',
    payload: { applicant_id: 'A-1004', income: 80000, loan_amount: 100000, age: 40, mock_credit_score: 540 } },
  { title: '5. Dependency failure then retry: RETRY_PENDING, then APPROVED', workflow: 'loan_approval', retry: true,
    payload: { applicant_id: 'A-1005', income: 70000, loan_amount: 100000, age: 29, mock_credit_score: 700,
      simulate_failure: { service: 'credit_bureau', fail_times: 1 } } },
  { title: '6. Dependency down beyond max attempts: MANUAL_REVIEW', workflow: 'loan_approval', retry: true,
    payload: { applicant_id: 'A-1006', income: 70000, loan_amount: 100000, age: 29, mock_credit_score: 700,
      simulate_failure: { service: 'credit_bureau', fail_times: 10 } } },
  { title: '7. Second workflow (vendor_approval), same engine: APPROVED', workflow: 'vendor_approval',
    payload: { vendor_id: 'V-77', country: 'IN', years_in_business: 5, annual_revenue: 500000 } },
];

(async () => {
  let md = '# Decision explanation examples\n\n_Generated by `npm run examples` from the real engine and the YAML configs in `config/workflows/`._\n\n';
  for (const s of scenarios) {
    const def = DEFS[s.workflow];
    const req = makeRequest(s.workflow, s.payload);
    await engine.run(req, def);
    while (s.retry && req.status === 'RETRY_PENDING') { // simulate what the retry worker / POST /retry does
      req.status = 'IN_PROGRESS';
      await engine.run(req, def);
    }
    const ex = audit.explain(req);
    md += `## ${s.title}\n\n**Input** (\`${s.workflow}\` v${def.version})\n\`\`\`json\n${JSON.stringify(s.payload, null, 2)}\n\`\`\`\n`;
    md += `**Outcome:** \`${req.status}\`  \n**Explanation:** ${ex.summary}\n\n**Audit trail**\n\n`;
    for (const step of ex.steps) {
      md += `${step.seq}. \`${step.type}\` (${step.stage || '-'}): ${step.message}\n`;
      (step.rules || []).forEach((r) => { md += `    - ${r.passed ? 'PASS' : 'FAIL'} **${r.ruleId}**: ${r.reason}\n`; });
    }
    md += `\n**State history:** ${req.stateHistory.map((h) => `${h.from}->${h.to}`).join(', ')}\n\n---\n\n`;
    console.log(`${s.title} => ${req.status}`);
  }
  const out = path.join(__dirname, '..', '..', 'docs', 'decision_examples.md');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, md);
  console.log('Wrote', out);
})();
